"""Generate the MysteryPath-Grid HP-tuning grid (λ × chunk_len × lr).

Tune a SMALL global grid on two representative cells + GatedDeltaNet, pick the
single global winner, lock it, then run the full 20M × 5-seed sweep with it.
Tuning is GLOBAL (not per-cell) on purpose — per-cell tuning would break the
fair-comparison framing.

Grid (3 × 3 × 2 = 18 combos) × 3 cells = 54 conditions:
    lambda_intrinsic ∈ {0.003, 0.01, 0.03}   (the exploration/exploitation dial;
                       the e3b bonus_mean ≈ 0.5, so this is the highest-leverage knob)
    chunk_len        ∈ {32, 64, 128}         (TBPTT window; the episode is 128 steps,
                       so 32 truncates at 1/4 and 128 = FULL-episode BPTT — no
                       truncation, the cleanest memory test. Longer windows let
                       strong cells train longer-range memory → sharper ranking.
                       NB: 128 is the most memory-hungry (≈4× the BPTT activations
                       of 32, on top of pixel obs + e3b) — most OOM-prone, watch it.)
    lr               ∈ {1e-4, 2.5e-4}        (stability vs speed; some `none` critics
                       diverged at 2.5e-4)

All runs use intrinsic=e3b_idm (λ is only meaningful with a bonus). Everything
else mirrors the MysteryPath-Grid baseline. Shorter budget (5M) — this is a
relative HP ranking, not the final result.

Cells: GRU (anchor), RetNet (current leader), GatedDeltaNet.

Seeds: the scripts honor $SEEDS (default "0 1 2"). For the grid run SEEDS="0"
(1 seed × 36 = 36 runs); reserve multi-seed for the locked winner.

Usage:
    python experiments/mysterypath_hpsweep/generate_configs.py
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
sys.path.insert(0, str(REPO_ROOT))
from train import DEFAULT_CELL_KWARGS  # noqa: E402

ENV_NAME = "MysteryPath-Grid-v0"
CELLS = ["GRU", "RetNet", "GatedDeltaNet"]
INTRINSIC = "e3b_idm"
LAMBDAS = [0.003, 0.01, 0.03]
CHUNK_LENS = [32, 64, 128]   # 128 = FULL-episode BPTT (episode is 128 steps)
LRS = [1.0e-4, 2.5e-4]
TUNE_TIMESTEPS = 5_000_000
WANDB_PROJECT = "memrl-mpg-hpsweep"

BASE = {
    "env_name": ENV_NAME,
    "n_envs": 16,
    "encoder_dim": 128,
    "encoder_hidden": 256,
    "n_steps": 512,
    "n_epochs": 4,
    "gamma": 0.995,
    "gae_lambda": 0.95,
    "clip_range": 0.2,
    "ent_coef": 0.008,
    "vf_coef": 1.0,
    "max_grad_norm": 0.5,
    "target_kl": 0.05,
    "n_chunks_per_batch": 32,
    "eval_every_rollouts": 5,
    "n_eval_episodes": 20,
}


def _lam_tag(x: float) -> str:
    return ("%g" % x).replace(".", "p")          # 0.003 -> 0p003


def _lr_tag(x: float) -> str:
    return ("%g" % x).replace(".", "p").replace("-", "")  # 0.0001 -> 0p0001, 0.00025 -> 0p00025


def build_cfg(cell: str, lam: float, ck: int, lr: float, intrinsic: str = INTRINSIC) -> dict:
    ordered = {
        "env_name": BASE["env_name"],
        "n_envs": BASE["n_envs"],
        "total_timesteps": TUNE_TIMESTEPS,
        "seed": 0,
        "cell": {"name": cell, "kwargs": dict(DEFAULT_CELL_KWARGS[cell])},
        "encoder_dim": BASE["encoder_dim"],
        "encoder_hidden": BASE["encoder_hidden"],
        "lr": lr,
        "n_steps": BASE["n_steps"],
        "n_epochs": BASE["n_epochs"],
        "gamma": BASE["gamma"],
        "gae_lambda": BASE["gae_lambda"],
        "clip_range": BASE["clip_range"],
        "ent_coef": BASE["ent_coef"],
        "vf_coef": BASE["vf_coef"],
        "max_grad_norm": BASE["max_grad_norm"],
        "target_kl": BASE["target_kl"],
        "chunk_len": ck,
        "n_chunks_per_batch": BASE["n_chunks_per_batch"],
        "intrinsic": intrinsic,
        "eval_every_rollouts": BASE["eval_every_rollouts"],
        "n_eval_episodes": BASE["n_eval_episodes"],
        "wandb": True,
        "wandb_project": WANDB_PROJECT,
    }
    if intrinsic != "none":
        ordered["lambda_intrinsic"] = lam
    return ordered


_SCRIPT_TEMPLATE = """\
#!/usr/bin/env bash
# AUTO-GENERATED by generate_configs.py — regenerate, don't hand-edit.
# MysteryPath HP-sweep: __TAG__ (e3b_idm). Honors PYTHON DEVICE RUNS_DIR SEEDS
# PARALLEL EXTRA. For the grid run with SEEDS="0".
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$HERE/../../.." && pwd)"
cd "$REPO_ROOT"
if [[ -z "${PYTHON:-}" ]]; then
  if [[ -x ".venv/bin/python" ]]; then PYTHON=".venv/bin/python"; else PYTHON="python"; fi
fi
DEVICE="${DEVICE:-cuda}"; RUNS_DIR="${RUNS_DIR:-runs/mysterypath_hpsweep}"
SEEDS="${SEEDS:-0 1 2}"; PARALLEL="${PARALLEL:-1}"; EXTRA="${EXTRA:-}"
CFG="$HERE/../configs/__CFG__"
LOGDIR="$HERE/../_logs"; mkdir -p "$LOGDIR"
TAG="__TAG__"
echo "[$TAG] python=$PYTHON device=$DEVICE seeds=[$SEEDS] parallel=$PARALLEL"
pids=()
for s in $SEEDS; do
  if [[ "$PARALLEL" == "1" ]]; then
    "$PYTHON" -m train --config "$CFG" --seed "$s" \\
        --runs-dir "$RUNS_DIR" --device "$DEVICE" $EXTRA \\
        > "$LOGDIR/${TAG}_seed${s}.log" 2>&1 &
    pids+=("$!")
    echo "  launched $TAG seed=$s (pid $!)"
  else
    "$PYTHON" -m train --config "$CFG" --seed "$s" \\
        --runs-dir "$RUNS_DIR" --device "$DEVICE" $EXTRA
  fi
done
if [[ "$PARALLEL" == "1" ]]; then
  fail=0; for p in "${pids[@]}"; do wait "$p" || fail=1; done
  [[ "$fail" == "0" ]] || { echo "[$TAG] a seed FAILED — see $LOGDIR"; exit 1; }
fi
echo "[$TAG] done."
"""

_RUN_ALL_TEMPLATE = """\
#!/usr/bin/env bash
# AUTO-GENERATED. Run every HP-sweep condition (serial; seeds parallel within).
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
for s in "$HERE"/hp_*.sh; do echo "=== $(basename "$s") ==="; bash "$s"; done
echo "All HP-sweep conditions done."
"""


def main() -> None:
    cfg_dir = HERE / "configs"; scr_dir = HERE / "scripts"
    cfg_dir.mkdir(parents=True, exist_ok=True); scr_dir.mkdir(parents=True, exist_ok=True)
    n = 0
    for cell in CELLS:
        for lam in LAMBDAS:
            for ck in CHUNK_LENS:
                for lr in LRS:
                    tag = f"{cell}_lam{_lam_tag(lam)}_ck{ck}_lr{_lr_tag(lr)}"
                    cfg = build_cfg(cell, lam, ck, lr)
                    cfg_name = f"mpg_hp_{tag}.yaml"
                    with open(cfg_dir / cfg_name, "w") as f:
                        yaml.safe_dump(cfg, f, sort_keys=False)
                    body = (_SCRIPT_TEMPLATE.replace("__CFG__", cfg_name).replace("__TAG__", tag))
                    p = scr_dir / f"hp_{tag}.sh"; p.write_text(body); os.chmod(p, 0o755)
                    n += 1
    # Curiosity arm: full-episode BPTT (ck128) on PLAIN PPO (no exploration),
    # 3 cells — does the long window alone (no bonus) move the `none` baseline?
    for cell in CELLS:
        ck, lr = 128, 2.5e-4
        cfg = build_cfg(cell, lam=0.0, ck=ck, lr=lr, intrinsic="none")
        tag = f"{cell}_none_ck{ck}_lr{_lr_tag(lr)}"
        with open(cfg_dir / f"mpg_hp_{tag}.yaml", "w") as f:
            yaml.safe_dump(cfg, f, sort_keys=False)
        p = scr_dir / f"hp_{tag}.sh"
        p.write_text(_SCRIPT_TEMPLATE.replace("__CFG__", f"mpg_hp_{tag}.yaml").replace("__TAG__", tag))
        os.chmod(p, 0o755)
        n += 1

    ra = scr_dir / "run_all.sh"; ra.write_text(_RUN_ALL_TEMPLATE); os.chmod(ra, 0o755)
    print(f"env={ENV_NAME}  project={WANDB_PROJECT}  budget={TUNE_TIMESTEPS//10**6}M")
    print(f"cells={CELLS}")
    print(f"grid: lambda={LAMBDAS} x chunk_len={CHUNK_LENS} x lr={LRS}")
    print(f"wrote {n} configs + {n} scripts (+ run_all.sh) -> {HERE}")
    print(f"= {n} conditions (run SEEDS=0 for the grid -> {n} runs)")


if __name__ == "__main__":
    main()
