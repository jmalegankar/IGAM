"""Generate the ObstructedMaze-1Q 2x2 ablation (memory x exploration ENTANGLED).

A SECOND entangled env alongside S13, with a DIFFERENT mechanic, so the
"you need both memory AND exploration" finding isn't a single-env artifact.

MiniGrid-ObstructedMaze-1Q: keys are hidden inside boxes, behind locked doors.
The agent must (a) EXPLORE hard — sparse reward, search rooms, open boxes/doors
— and (b) REMEMBER what it saw (key colour, box/door locations) under the 7x7
egocentric view. Distinct from S13's 1-bit cue-recall (this is *spatial* working
memory), so reproducing the pattern here generalizes it. It's also a NovelD/E3B
benchmark, so the bonus is known to bite.

The clean 2x2 ablation — {memory cell, Memoryless} x {none, bonus}:

                 none                 bonus
    Memoryless   fail                 fail   (memory needed)
    GRU          fail (explore needed) SOLVE  (both needed)

Only the both-corner solves ⇒ memory ∧ exploration are jointly required.

  cells       = {GRU, Memoryless}
  intrinsics  = {none, noveld, e3b_idm}
  → 6 conditions x 3 seeds = 18 runs.

Obs is the 7x7x20 image, so the SAME CNN encoder as S13 is selected automatically
(by obs space, cell-independent). HPs mirror the S13 baseline (image MiniGrid,
chunk_len=32) so the two entangled envs are methodologically comparable; ent_coef
kept low so the intrinsic bonus — not entropy — is the exploration driver, which
is what makes the `none` column fail cleanly.

Usage:
    python experiments/obstructedmaze_1q/generate_configs.py
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
sys.path.insert(0, str(REPO_ROOT))
from train import DEFAULT_CELL_KWARGS  # noqa: E402

ENV_NAME = "MiniGrid-ObstructedMaze-1Q-v1"
CELLS = ["GRU", "Memoryless"]
INTRINSICS = ["none", "noveld", "e3b_idm"]
LAMBDA_INTRINSIC = 0.01

# HPs mirror the S13 baseline (same image-MiniGrid CNN regime).
BASE = {
    "env_name": ENV_NAME,
    "n_envs": 16,
    "total_timesteps": 10_000_000,
    "encoder_dim": 128,
    "encoder_hidden": 256,
    "lr": 3.0e-4,
    "n_steps": 512,
    "n_epochs": 4,
    "gamma": 0.999,
    "gae_lambda": 0.98,
    "clip_range": 0.2,
    "ent_coef": 0.008,        # low on purpose: the bonus is the exploration driver
    "vf_coef": 1.0,
    "max_grad_norm": 0.5,
    "target_kl": 0.05,
    "chunk_len": 32,
    "n_chunks_per_batch": 32,
    "eval_every_rollouts": 5,
    "n_eval_episodes": 20,
    "wandb": True,
    "wandb_project": "memrl-obstructedmaze-1q",
}


def build_cfg(cell: str, intrinsic: str) -> dict:
    if cell not in DEFAULT_CELL_KWARGS:
        raise KeyError(f"{cell} not in train.py DEFAULT_CELL_KWARGS")
    ordered = {
        "env_name": BASE["env_name"],
        "n_envs": BASE["n_envs"],
        "total_timesteps": BASE["total_timesteps"],
        "seed": 0,                      # overridden per run via --seed
        "cell": {"name": cell, "kwargs": dict(DEFAULT_CELL_KWARGS[cell])},
        "encoder_dim": BASE["encoder_dim"],
        "encoder_hidden": BASE["encoder_hidden"],
    }
    for k in ("lr", "n_steps", "n_epochs", "gamma", "gae_lambda", "clip_range",
              "ent_coef", "vf_coef", "max_grad_norm", "target_kl",
              "chunk_len", "n_chunks_per_batch"):
        ordered[k] = BASE[k]
    ordered["intrinsic"] = intrinsic
    if intrinsic != "none":
        ordered["lambda_intrinsic"] = LAMBDA_INTRINSIC
    for k in ("eval_every_rollouts", "n_eval_episodes", "wandb", "wandb_project"):
        ordered[k] = BASE[k]
    return ordered


_SCRIPT_TEMPLATE = """\
#!/usr/bin/env bash
# AUTO-GENERATED by generate_configs.py — regenerate, don't hand-edit.
# ObstructedMaze-1Q: __CELL__ + __INTRINSIC__, all seeds (parallel).
# Env knobs: PYTHON DEVICE RUNS_DIR SEEDS PARALLEL EXTRA (same as S13 scripts).
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$HERE/../../.." && pwd)"
cd "$REPO_ROOT"
if [[ -z "${PYTHON:-}" ]]; then
  if [[ -x ".venv/bin/python" ]]; then PYTHON=".venv/bin/python"; else PYTHON="python"; fi
fi
DEVICE="${DEVICE:-cuda}"; RUNS_DIR="${RUNS_DIR:-runs/obstructedmaze_1q}"
SEEDS="${SEEDS:-0 1 2}"; PARALLEL="${PARALLEL:-1}"; EXTRA="${EXTRA:-}"
CFG="$HERE/../configs/__CFG__"
LOGDIR="$HERE/../_logs"; mkdir -p "$LOGDIR"
TAG="__TAG__"
echo "[$TAG] python=$PYTHON device=$DEVICE seeds=[$SEEDS] parallel=$PARALLEL"
pids=()
for s in $SEEDS; do
  if [[ "$PARALLEL" == "1" ]]; then
    "$PYTHON" -m train --config "$CFG" --seed "$s" \\
        --runs-dir "$RUNS_DIR" --device "$DEVICE" $EXTRA \\
        > "$LOGDIR/${TAG}_seed${s}.log" 2>&1 &
    pids+=("$!")
    echo "  launched $TAG seed=$s (pid $!) → $LOGDIR/${TAG}_seed${s}.log"
  else
    echo "  $TAG seed=$s (sequential)"
    "$PYTHON" -m train --config "$CFG" --seed "$s" \\
        --runs-dir "$RUNS_DIR" --device "$DEVICE" $EXTRA
  fi
done
if [[ "$PARALLEL" == "1" ]]; then
  fail=0
  for p in "${pids[@]}"; do wait "$p" || fail=1; done
  [[ "$fail" == "0" ]] || { echo "[$TAG] a seed FAILED — see $LOGDIR"; exit 1; }
fi
echo "[$TAG] all seeds done."
"""

_RUN_ALL_TEMPLATE = """\
#!/usr/bin/env bash
# AUTO-GENERATED. Run every ObstructedMaze-1Q leaf script (conditions serial,
# seeds parallel within). All env knobs propagate.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
for s in "$HERE"/run_*.sh "$HERE"/explore_*.sh; do
  bn="$(basename "$s")"
  [[ "$bn" == "run_all.sh" ]] && continue
  echo "=== $bn ==="
  bash "$s"
done
echo "All ObstructedMaze-1Q conditions done."
"""


def main() -> None:
    cfg_dir = HERE / "configs"
    scr_dir = HERE / "scripts"
    cfg_dir.mkdir(parents=True, exist_ok=True)
    scr_dir.mkdir(parents=True, exist_ok=True)

    n_cfg = n_scr = 0
    for cell in CELLS:
        for intrinsic in INTRINSICS:
            cfg = build_cfg(cell, intrinsic)
            cfg_name = f"om1q_{cell}_{intrinsic}.yaml"
            with open(cfg_dir / cfg_name, "w") as f:
                yaml.safe_dump(cfg, f, sort_keys=False)
            n_cfg += 1

            if intrinsic == "none":
                scr_name, tag = f"run_{cell}.sh", f"{cell}_none"
            else:
                scr_name, tag = f"explore_{cell}_{intrinsic}.sh", f"{cell}_{intrinsic}"
            body = (_SCRIPT_TEMPLATE
                    .replace("__CELL__", cell)
                    .replace("__INTRINSIC__", intrinsic)
                    .replace("__CFG__", cfg_name)
                    .replace("__TAG__", tag))
            p = scr_dir / scr_name
            p.write_text(body)
            os.chmod(p, 0o755)
            n_scr += 1

    run_all = scr_dir / "run_all.sh"
    run_all.write_text(_RUN_ALL_TEMPLATE)
    os.chmod(run_all, 0o755)

    print(f"env={ENV_NAME}")
    print(f"cells={CELLS} intrinsics={INTRINSICS}")
    print(f"wrote {n_cfg} configs + {n_scr} scripts (+ run_all.sh) → {HERE}")
    print(f"2x2 ablation = {n_cfg} conditions x 3 seeds = {n_cfg*3} runs")


if __name__ == "__main__":
    main()
