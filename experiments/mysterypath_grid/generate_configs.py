"""Generate the MysteryPath-Grid 2x4 ablation (memory + exploration ENTANGLED).

MysteryPath (memory-gym; Pleines et al. 2023): the agent must cross an INVISIBLE,
procedurally-generated path from origin to goal. Step off the path → teleported
back to the origin. Nothing about the path is observable, so there's no reactive
shortcut: the agent must DISCOVER the path by trial (exploration) AND REMEMBER
which tiles are safe across attempts (memory). That makes it genuinely
memory-REQUIRED *and* exploration-bottlenecked — the clean entangled env that
RedBlueDoors (solvable without memory) could not be.

The 2x4 ablation — {GRU, Memoryless} x {none, e3b_idm, rnd, noveld}:

                  none            +bonus
    Memoryless    fail            fail   (memory needed — can't recall the path)
    GRU           fail/partial    SOLVE  (needs exploration to find it + memory)

  = 8 conditions x 3 seeds = 24 runs.

Obs is 84x84x3 RGB ⇒ the dedicated Nature-DQN PixelEncoder (make_encoder routes
large RGB frames to it, separate from the MiniGrid grid CNN). Action is
Discrete(4) (MysteryPath-Grid; the non-Grid MysteryPath-v0 is MultiDiscrete and
unsupported). HPs mirror the S13 baseline except where the pixel/horizon regime
differs. ent_coef kept low so the intrinsic bonus — not entropy — drives the
path search.

Install (local + Docker): pip install pygame>=2.6 && pip install memory-gym --no-deps
(memory-gym pins pygame==2.4.0, which has no py3.12 wheel).

Usage:
    python experiments/mysterypath_grid/generate_configs.py
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
sys.path.insert(0, str(REPO_ROOT))
from train import DEFAULT_CELL_KWARGS  # noqa: E402

ENV_NAME = "MysteryPath-Grid-v0"

# Memory-ranking arm: which cells solve MysteryPath with plain PPO (intrinsic=
# none)? The 11-cell lineup, same as S13 / RedBlueDoors — directly comparable.
RANKING_CELLS = [
    "GRU", "LSTM", "mLSTM", "LRU", "Mamba2", "FFM",
    "GatedDeltaNet", "SHM", "GTrXL", "RetNet", "LinearTransformer",
]
# Entanglement arm: does an exploration bonus help a memory cell (GRU), and can
# it substitute for memory (Memoryless control)? Crossed with the bonuses.
EXPLORE_CELLS = ["GRU", "Memoryless"]
EXPLORE_INTRINSICS = ["none", "e3b_idm", "rnd", "noveld"]
LAMBDA_INTRINSIC = 0.01

# Per-cell overrides, matching the S13 / RedBlueDoors baselines.
PER_CELL_LR = {"Mamba2": 1.25e-4}                       # half the pixel base lr
PER_CELL_KWARGS_OVERRIDES = {"GTrXL": {"mem_len": 128}}

BASE = {
    "env_name": ENV_NAME,
    "n_envs": 16,
    "total_timesteps": 10_000_000,
    "encoder_dim": 128,
    "encoder_hidden": 256,
    "lr": 2.5e-4,             # Nature-CNN pixel default (slightly below S13's 3e-4)
    "n_steps": 512,
    "n_epochs": 4,
    "gamma": 0.995,
    "gae_lambda": 0.95,
    "clip_range": 0.2,
    "ent_coef": 0.008,        # low: the bonus is the exploration driver
    "vf_coef": 1.0,
    "max_grad_norm": 0.5,
    "target_kl": 0.05,
    "chunk_len": 32,
    "n_chunks_per_batch": 32,
    "eval_every_rollouts": 5,
    "n_eval_episodes": 20,
    "wandb": True,
    "wandb_project": "memrl-mysterypath-grid",
}


def build_cfg(cell: str, intrinsic: str) -> dict:
    if cell not in DEFAULT_CELL_KWARGS:
        raise KeyError(f"{cell} not in train.py DEFAULT_CELL_KWARGS")
    kwargs = dict(DEFAULT_CELL_KWARGS[cell])
    kwargs.update(PER_CELL_KWARGS_OVERRIDES.get(cell, {}))
    ordered = {
        "env_name": BASE["env_name"],
        "n_envs": BASE["n_envs"],
        "total_timesteps": BASE["total_timesteps"],
        "seed": 0,                      # overridden per run via --seed
        "cell": {"name": cell, "kwargs": kwargs},
        "encoder_dim": BASE["encoder_dim"],
        "encoder_hidden": BASE["encoder_hidden"],
        "lr": PER_CELL_LR.get(cell, BASE["lr"]),
    }
    for k in ("n_steps", "n_epochs", "gamma", "gae_lambda", "clip_range",
              "ent_coef", "vf_coef", "max_grad_norm", "target_kl",
              "chunk_len", "n_chunks_per_batch"):
        ordered[k] = BASE[k]
    ordered["intrinsic"] = intrinsic
    if intrinsic != "none":
        ordered["lambda_intrinsic"] = LAMBDA_INTRINSIC
    for k in ("eval_every_rollouts", "n_eval_episodes", "wandb", "wandb_project"):
        ordered[k] = BASE[k]
    return ordered


_SCRIPT_TEMPLATE = """\
#!/usr/bin/env bash
# AUTO-GENERATED by generate_configs.py — regenerate, don't hand-edit.
# MysteryPath-Grid: __CELL__ + __INTRINSIC__, all seeds (parallel).
# Env knobs: PYTHON DEVICE RUNS_DIR SEEDS PARALLEL EXTRA (same as S13 scripts).
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$HERE/../../.." && pwd)"
cd "$REPO_ROOT"
if [[ -z "${PYTHON:-}" ]]; then
  if [[ -x ".venv/bin/python" ]]; then PYTHON=".venv/bin/python"; else PYTHON="python"; fi
fi
DEVICE="${DEVICE:-cuda}"; RUNS_DIR="${RUNS_DIR:-runs/mysterypath_grid}"
SEEDS="${SEEDS:-0 1 2}"; PARALLEL="${PARALLEL:-1}"; EXTRA="${EXTRA:-}"
CFG="$HERE/../configs/__CFG__"
LOGDIR="$HERE/../_logs"; mkdir -p "$LOGDIR"
TAG="__TAG__"
echo "[$TAG] python=$PYTHON device=$DEVICE seeds=[$SEEDS] parallel=$PARALLEL"
pids=()
for s in $SEEDS; do
  if [[ "$PARALLEL" == "1" ]]; then
    "$PYTHON" -m train --config "$CFG" --seed "$s" \\
        --runs-dir "$RUNS_DIR" --device "$DEVICE" $EXTRA \\
        > "$LOGDIR/${TAG}_seed${s}.log" 2>&1 &
    pids+=("$!")
    echo "  launched $TAG seed=$s (pid $!) → $LOGDIR/${TAG}_seed${s}.log"
  else
    echo "  $TAG seed=$s (sequential)"
    "$PYTHON" -m train --config "$CFG" --seed "$s" \\
        --runs-dir "$RUNS_DIR" --device "$DEVICE" $EXTRA
  fi
done
if [[ "$PARALLEL" == "1" ]]; then
  fail=0
  for p in "${pids[@]}"; do wait "$p" || fail=1; done
  [[ "$fail" == "0" ]] || { echo "[$TAG] a seed FAILED — see $LOGDIR"; exit 1; }
fi
echo "[$TAG] all seeds done."
"""

_RUN_ALL_TEMPLATE = """\
#!/usr/bin/env bash
# AUTO-GENERATED. Run every MysteryPath-Grid leaf script (conditions serial,
# seeds parallel within). All env knobs propagate.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
for s in "$HERE"/run_*.sh "$HERE"/explore_*.sh; do
  bn="$(basename "$s")"
  [[ "$bn" == "run_all.sh" ]] && continue
  echo "=== $bn ==="
  bash "$s"
done
echo "All MysteryPath-Grid conditions done."
"""


def main() -> None:
    cfg_dir = HERE / "configs"
    scr_dir = HERE / "scripts"
    cfg_dir.mkdir(parents=True, exist_ok=True)
    scr_dir.mkdir(parents=True, exist_ok=True)

    # Union of the two arms, order-preserving + deduped (GRU+none appears in both).
    ranking = [(c, "none") for c in RANKING_CELLS]
    explore = [(c, m) for c in EXPLORE_CELLS for m in EXPLORE_INTRINSICS]
    seen: set[tuple[str, str]] = set()
    conditions: list[tuple[str, str]] = []
    for cond in ranking + explore:
        if cond not in seen:
            seen.add(cond)
            conditions.append(cond)

    n = 0
    for cell, intrinsic in conditions:
        cfg = build_cfg(cell, intrinsic)
        cfg_name = f"mpg_{cell}_{intrinsic}.yaml"
        with open(cfg_dir / cfg_name, "w") as f:
            yaml.safe_dump(cfg, f, sort_keys=False)

        if intrinsic == "none":
            scr_name, tag = f"run_{cell}.sh", f"{cell}_none"
        else:
            scr_name, tag = f"explore_{cell}_{intrinsic}.sh", f"{cell}_{intrinsic}"
        body = (_SCRIPT_TEMPLATE
                .replace("__CELL__", cell)
                .replace("__INTRINSIC__", intrinsic)
                .replace("__CFG__", cfg_name)
                .replace("__TAG__", tag))
        p = scr_dir / scr_name
        p.write_text(body)
        os.chmod(p, 0o755)
        n += 1

    run_all = scr_dir / "run_all.sh"
    run_all.write_text(_RUN_ALL_TEMPLATE)
    os.chmod(run_all, 0o755)

    print(f"env={ENV_NAME}")
    print(f"ranking: {len(RANKING_CELLS)} cells x none")
    print(f"entanglement: {EXPLORE_CELLS} x {EXPLORE_INTRINSICS}")
    print(f"wrote {n} configs + {n} scripts (+ run_all.sh) → {HERE}")
    print(f"total = {n} conditions x 3 seeds = {n*3} runs")


if __name__ == "__main__":
    main()
