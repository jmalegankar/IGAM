"""Generate the MysteryPath-Grid 20M × 5-seed HEADLINE sweep.

Locked global HPs from the memrl-mpg-hpsweep tune (winner by the maximin /
fair-comparison criterion — best worst-cell, still climbing, no OOM, not the
RetNet-skewed ck128 combo):

    intrinsic        = e3b_idm
    lambda_intrinsic = 0.03      (λ was the decisive knob: 0.03 > 0.01 > 0.003)
    chunk_len        = 64        (balanced + climbing; ck128 was RetNet-skewed + OOM)
    lr               = 1e-4      (low → stabilizes the weaker cells)

GLOBAL HPs — identical across all cells (the fair-comparison story). The only
per-cell setting is GTrXL's attention window (mem_len=128, an architecture/
capacity knob, not optimizer tuning — same exception as S13).

  cells = 11 lineup + Memoryless (control) ; intrinsic = e3b_idm ; 5 seeds
  → 12 cells × 5 seeds = 60 runs.

Packing: 2 cells PER GPU (the OOM-safe choice — 3/GPU crashed in the hpsweep).
One script per (seed, cell-pair): 6 pairs × 5 seeds = 30 GPU jobs, each running
2 cells in parallel at one seed. Configs are per-cell (seed via --seed), so the
default wandb name "<cell>-e3b_idm-seed<n>" is already unique — no run_name hack
needed (unlike the hpsweep, where HPs varied per cell).

Usage:
    python experiments/mysterypath_20m/generate_configs.py
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
sys.path.insert(0, str(REPO_ROOT))
from train import DEFAULT_CELL_KWARGS  # noqa: E402

CELLS = [
    "GRU", "LSTM", "mLSTM", "LRU", "Mamba2", "FFM",
    "GatedDeltaNet", "SHM", "GTrXL", "RetNet", "LinearTransformer", "Memoryless",
]
SEEDS = [0, 1, 2, 3, 4]
# 2 cells per GPU — consecutive pairs of the lineup (+ Memoryless paired last).
PAIRS = [CELLS[i:i + 2] for i in range(0, len(CELLS), 2)]   # 6 pairs

PER_CELL_KWARGS_OVERRIDES = {"GTrXL": {"mem_len": 128}}     # architecture, not tuning

BASE = {
    "env_name": "MysteryPath-Grid-v0",
    "n_envs": 16,
    "total_timesteps": 20_000_000,
    "encoder_dim": 128,
    "encoder_hidden": 256,
    "lr": 1.0e-4,                 # WINNER
    "n_steps": 512,
    "n_epochs": 4,
    "gamma": 0.995,
    "gae_lambda": 0.95,
    "clip_range": 0.2,
    "ent_coef": 0.008,
    "vf_coef": 1.0,
    "max_grad_norm": 0.5,
    "target_kl": 0.05,
    "chunk_len": 64,              # WINNER
    "n_chunks_per_batch": 32,
    "intrinsic": "e3b_idm",
    "lambda_intrinsic": 0.03,     # WINNER
    "eval_every_rollouts": 10,    # ~244 evals over 20M
    "n_eval_episodes": 20,
    "wandb": True,
    "wandb_project": "memrl-mpg-20m",
}


def build_cfg(cell: str) -> dict:
    if cell not in DEFAULT_CELL_KWARGS:
        raise KeyError(f"{cell} not in train.py DEFAULT_CELL_KWARGS")
    kwargs = dict(DEFAULT_CELL_KWARGS[cell])
    kwargs.update(PER_CELL_KWARGS_OVERRIDES.get(cell, {}))
    ordered = {
        "env_name": BASE["env_name"],
        "n_envs": BASE["n_envs"],
        "total_timesteps": BASE["total_timesteps"],
        "seed": 0,                      # overridden per run via --seed
        "cell": {"name": cell, "kwargs": kwargs},
        "encoder_dim": BASE["encoder_dim"],
        "encoder_hidden": BASE["encoder_hidden"],
    }
    for k in ("lr", "n_steps", "n_epochs", "gamma", "gae_lambda", "clip_range",
              "ent_coef", "vf_coef", "max_grad_norm", "target_kl",
              "chunk_len", "n_chunks_per_batch", "intrinsic", "lambda_intrinsic",
              "eval_every_rollouts", "n_eval_episodes", "wandb", "wandb_project"):
        ordered[k] = BASE[k]
    return ordered


_SCRIPT_TEMPLATE = """\
#!/usr/bin/env bash
# AUTO-GENERATED by generate_configs.py — regenerate, don't hand-edit.
# 20M sweep: cells [__CELLS__] at seed __SEED__, in PARALLEL on ONE GPU (2/GPU).
# Knobs: PYTHON DEVICE RUNS_DIR EXTRA.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$HERE/../../.." && pwd)"
cd "$REPO_ROOT"
if [[ -z "${PYTHON:-}" ]]; then
  if [[ -x ".venv/bin/python" ]]; then PYTHON=".venv/bin/python"; else PYTHON="python"; fi
fi
DEVICE="${DEVICE:-cuda}"; RUNS_DIR="${RUNS_DIR:-runs/mysterypath_20m}"; EXTRA="${EXTRA:-}"
LOGDIR="$HERE/../_logs"; mkdir -p "$LOGDIR"
SEED="__SEED__"; CELLS="__CELLS__"
echo "[s$SEED | $CELLS] 2 cells parallel on one GPU"
pids=()
for cell in $CELLS; do
  CFG="$HERE/../configs/mpg20m_${cell}.yaml"
  "$PYTHON" -m train --config "$CFG" --seed "$SEED" \\
      --runs-dir "$RUNS_DIR" --device "$DEVICE" $EXTRA \\
      > "$LOGDIR/${cell}_seed${SEED}.log" 2>&1 &
  pids+=("$!"); echo "  launched $cell seed=$SEED (pid $!)"
done
fail=0; for p in "${pids[@]}"; do wait "$p" || fail=1; done
[[ "$fail" == "0" ]] || { echo "[s$SEED | $CELLS] a cell FAILED — see $LOGDIR"; exit 1; }
echo "[s$SEED | $CELLS] done."
"""

_RUN_ALL_TEMPLATE = """\
#!/usr/bin/env bash
# AUTO-GENERATED. Run every 20M (seed,pair) job serially (2 cells parallel within).
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
for s in "$HERE"/mpg20m_*.sh; do
  bn="$(basename "$s")"; [[ "$bn" == "run_all.sh" ]] && continue
  echo "=== $bn ==="; bash "$s"
done
echo "All 20M jobs done."
"""


def main() -> None:
    cfg_dir = HERE / "configs"; scr_dir = HERE / "scripts"
    cfg_dir.mkdir(parents=True, exist_ok=True); scr_dir.mkdir(parents=True, exist_ok=True)

    for cell in CELLS:
        with open(cfg_dir / f"mpg20m_{cell}.yaml", "w") as f:
            yaml.safe_dump(build_cfg(cell), f, sort_keys=False)

    n_scr = 0
    for seed in SEEDS:
        for pair in PAIRS:
            tag = f"s{seed}_{'-'.join(pair)}"
            body = (_SCRIPT_TEMPLATE
                    .replace("__SEED__", str(seed))
                    .replace("__CELLS__", " ".join(pair)))
            p = scr_dir / f"mpg20m_{tag}.sh"; p.write_text(body); os.chmod(p, 0o755)
            n_scr += 1
    ra = scr_dir / "run_all.sh"; ra.write_text(_RUN_ALL_TEMPLATE); os.chmod(ra, 0o755)

    print("env=MysteryPath-Grid-v0  project=memrl-mpg-20m  budget=20M")
    print(f"HPs: e3b_idm  λ=0.03  chunk_len=64  lr=1e-4  (GTrXL mem_len=128)")
    print(f"cells={len(CELLS)}  seeds={SEEDS}  pairs={len(PAIRS)} (2 cells/GPU)")
    print(f"wrote {len(CELLS)} configs + {n_scr} scripts (+ run_all.sh)")
    print(f"= {n_scr} GPU jobs (2 cells each) = {len(CELLS)*len(SEEDS)} runs")


if __name__ == "__main__":
    main()
