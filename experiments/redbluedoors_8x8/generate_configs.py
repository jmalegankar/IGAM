"""Generate the MiniGrid-RedBlueDoors-8x8 study (memory ranking + a memoryless
exploration control).

RedBlueDoors-8x8: two doors (red, blue) in an 8x8 room. The agent must open them
in order, which requires REMEMBERING which door it already opened (the order is
the hidden state). Modest exploration (small room), so this leans MEMORY — a good
companion to S13 / ObstructedMaze for a second memory-cell ranking on a different
mechanic (order-recall rather than cue-recall or spatial-search).

Two arms:
  1. MEMORY RANKING — cells x intrinsic=none (plain PPO). Which cells can remember
     the door order? (Expect strong cells solve, GRU/LSTM-class falter — as on
     S13 / RLBenchNet's MemoryS11.)
  2. MEMORYLESS EXPLORATION CONTROL — Memoryless x {e3b_idm, rnd, noveld} (+none).
     Can an exploration bonus substitute for memory? If a memoryless policy fails
     even WITH every bonus, memory is necessary and exploration cannot replace it.

  → 11 cells x none  +  Memoryless x {none, e3b_idm, rnd, noveld}
  = 15 conditions x 3 seeds = 45 runs.

Obs is the 7x7x20 image ⇒ SAME CNN encoder as S13 (auto-selected by obs space).
HPs mirror the S13 baseline so the memory rankings are directly comparable.

Usage:
    python experiments/redbluedoors_8x8/generate_configs.py
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
sys.path.insert(0, str(REPO_ROOT))
from train import DEFAULT_CELL_KWARGS  # noqa: E402

ENV_NAME = "MiniGrid-RedBlueDoors-8x8-v0"

# Memory ranking: the 11-cell lineup (same as S13), intrinsic=none.
CELLS = [
    "GRU", "LSTM", "mLSTM", "LRU", "Mamba2", "FFM",
    "GatedDeltaNet", "SHM", "GTrXL", "RetNet", "LinearTransformer",
]
# Memoryless control: can exploration substitute for memory? (+none baseline so
# we can tell whether a bonus actually moved the memoryless policy.)
MEMORYLESS_INTRINSICS = ["none", "e3b_idm", "rnd", "noveld"]
LAMBDA_INTRINSIC = 0.01

# Per-cell overrides — identical to the S13 baseline (documented there):
PER_CELL_LR = {"Mamba2": 1.5e-4}                 # SSM PPO-stability (RLBenchNet)
PER_CELL_KWARGS_OVERRIDES = {"GTrXL": {"mem_len": 128}}  # window > recall span

BASE = {
    "env_name": ENV_NAME,
    "n_envs": 16,
    "total_timesteps": 10_000_000,
    "encoder_dim": 128,
    "encoder_hidden": 256,
    "lr": 3.0e-4,
    "n_steps": 512,
    "n_epochs": 4,
    "gamma": 0.999,
    "gae_lambda": 0.98,
    "clip_range": 0.2,
    "ent_coef": 0.008,
    "vf_coef": 1.0,
    "max_grad_norm": 0.5,
    "target_kl": 0.05,
    "chunk_len": 32,
    "n_chunks_per_batch": 32,
    "eval_every_rollouts": 5,
    "n_eval_episodes": 20,
    "wandb": True,
    "wandb_project": "memrl-redbluedoors-8x8",
}


def build_cfg(cell: str, intrinsic: str) -> dict:
    if cell not in DEFAULT_CELL_KWARGS:
        raise KeyError(f"{cell} not in train.py DEFAULT_CELL_KWARGS")
    kwargs = dict(DEFAULT_CELL_KWARGS[cell])
    kwargs.update(PER_CELL_KWARGS_OVERRIDES.get(cell, {}))
    ordered = {
        "env_name": BASE["env_name"],
        "n_envs": BASE["n_envs"],
        "total_timesteps": BASE["total_timesteps"],
        "seed": 0,                      # overridden per run via --seed
        "cell": {"name": cell, "kwargs": kwargs},
        "encoder_dim": BASE["encoder_dim"],
        "encoder_hidden": BASE["encoder_hidden"],
        "lr": PER_CELL_LR.get(cell, BASE["lr"]),
    }
    for k in ("n_steps", "n_epochs", "gamma", "gae_lambda", "clip_range",
              "ent_coef", "vf_coef", "max_grad_norm", "target_kl",
              "chunk_len", "n_chunks_per_batch"):
        ordered[k] = BASE[k]
    ordered["intrinsic"] = intrinsic
    if intrinsic != "none":
        ordered["lambda_intrinsic"] = LAMBDA_INTRINSIC
    for k in ("eval_every_rollouts", "n_eval_episodes", "wandb", "wandb_project"):
        ordered[k] = BASE[k]
    return ordered


_SCRIPT_TEMPLATE = """\
#!/usr/bin/env bash
# AUTO-GENERATED by generate_configs.py — regenerate, don't hand-edit.
# RedBlueDoors-8x8: __CELL__ + __INTRINSIC__, all seeds (parallel).
# Env knobs: PYTHON DEVICE RUNS_DIR SEEDS PARALLEL EXTRA (same as S13 scripts).
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$HERE/../../.." && pwd)"
cd "$REPO_ROOT"
if [[ -z "${PYTHON:-}" ]]; then
  if [[ -x ".venv/bin/python" ]]; then PYTHON=".venv/bin/python"; else PYTHON="python"; fi
fi
DEVICE="${DEVICE:-cuda}"; RUNS_DIR="${RUNS_DIR:-runs/redbluedoors_8x8}"
SEEDS="${SEEDS:-0 1 2}"; PARALLEL="${PARALLEL:-1}"; EXTRA="${EXTRA:-}"
CFG="$HERE/../configs/__CFG__"
LOGDIR="$HERE/../_logs"; mkdir -p "$LOGDIR"
TAG="__TAG__"
echo "[$TAG] python=$PYTHON device=$DEVICE seeds=[$SEEDS] parallel=$PARALLEL"
pids=()
for s in $SEEDS; do
  if [[ "$PARALLEL" == "1" ]]; then
    "$PYTHON" -m train --config "$CFG" --seed "$s" \\
        --runs-dir "$RUNS_DIR" --device "$DEVICE" $EXTRA \\
        > "$LOGDIR/${TAG}_seed${s}.log" 2>&1 &
    pids+=("$!")
    echo "  launched $TAG seed=$s (pid $!) → $LOGDIR/${TAG}_seed${s}.log"
  else
    echo "  $TAG seed=$s (sequential)"
    "$PYTHON" -m train --config "$CFG" --seed "$s" \\
        --runs-dir "$RUNS_DIR" --device "$DEVICE" $EXTRA
  fi
done
if [[ "$PARALLEL" == "1" ]]; then
  fail=0
  for p in "${pids[@]}"; do wait "$p" || fail=1; done
  [[ "$fail" == "0" ]] || { echo "[$TAG] a seed FAILED — see $LOGDIR"; exit 1; }
fi
echo "[$TAG] all seeds done."
"""

_RUN_ALL_TEMPLATE = """\
#!/usr/bin/env bash
# AUTO-GENERATED. Run every RedBlueDoors-8x8 leaf script (conditions serial,
# seeds parallel within). All env knobs propagate.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
for s in "$HERE"/run_*.sh "$HERE"/explore_*.sh; do
  bn="$(basename "$s")"
  [[ "$bn" == "run_all.sh" ]] && continue
  echo "=== $bn ==="
  bash "$s"
done
echo "All RedBlueDoors-8x8 conditions done."
"""


def main() -> None:
    cfg_dir = HERE / "configs"
    scr_dir = HERE / "scripts"
    cfg_dir.mkdir(parents=True, exist_ok=True)
    scr_dir.mkdir(parents=True, exist_ok=True)

    conditions = [(c, "none") for c in CELLS] + \
                 [("Memoryless", m) for m in MEMORYLESS_INTRINSICS]

    n = 0
    for cell, intrinsic in conditions:
        cfg = build_cfg(cell, intrinsic)
        cfg_name = f"rbd_{cell}_{intrinsic}.yaml"
        with open(cfg_dir / cfg_name, "w") as f:
            yaml.safe_dump(cfg, f, sort_keys=False)

        if intrinsic == "none":
            scr_name, tag = f"run_{cell}.sh", f"{cell}_none"
        else:
            scr_name, tag = f"explore_{cell}_{intrinsic}.sh", f"{cell}_{intrinsic}"
        body = (_SCRIPT_TEMPLATE
                .replace("__CELL__", cell)
                .replace("__INTRINSIC__", intrinsic)
                .replace("__CFG__", cfg_name)
                .replace("__TAG__", tag))
        p = scr_dir / scr_name
        p.write_text(body)
        os.chmod(p, 0o755)
        n += 1

    run_all = scr_dir / "run_all.sh"
    run_all.write_text(_RUN_ALL_TEMPLATE)
    os.chmod(run_all, 0o755)

    print(f"env={ENV_NAME}")
    print(f"memory ranking: {len(CELLS)} cells x none")
    print(f"memoryless control: Memoryless x {MEMORYLESS_INTRINSICS}")
    print(f"wrote {n} configs + {n} scripts (+ run_all.sh) → {HERE}")
    print(f"total = {n} conditions x 3 seeds = {n*3} runs")


if __name__ == "__main__":
    main()
